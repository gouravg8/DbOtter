import assert from "node:assert/strict";
import { test } from "node:test";
import type { ColumnInfo } from "./api.ts";
import { buildEdits, changedRows, editability, simpleSelect, withPending } from "./edits.ts";

const col = (name: string, extra: Partial<ColumnInfo> = {}): ColumnInfo => ({
  name,
  dataType: "text",
  nullable: true,
  default: null,
  generated: null,
  primaryKey: false,
  comment: null,
  ...extra,
});
const table = [
  col("id", { primaryKey: true, dataType: "integer" }),
  col("name"),
  col("avatar", { dataType: "bytea" }),
  col("total", { generated: "GENERATED ALWAYS AS (a + b) STORED" }),
  col("seq", { generated: "GENERATED BY DEFAULT AS IDENTITY" }),
];

test("which columns can be edited", () => {
  assert.deepEqual(editability(["id", "name", "avatar", "total", "seq"], table), {
    ok: true,
    pk: ["id"],
    editable: [true, true, false, false, true],
  });
  // a query naming only some columns; `x` is computed
  assert.deepEqual(editability(["id", "name", "x"], table, ["id", "name"]), { ok: true, pk: ["id"], editable: [true, true, false] });
  assert.equal(editability(["name"], table).ok, false);
  assert.equal(editability(["id", "id", "name"], table).ok, false);
  assert.match((editability(["a"], [col("a")]) as { reason: string }).reason, /no primary key/);
});

test("changed cells become one edit per row, keyed by the loaded primary key", () => {
  const rows = [
    ["1", "a"],
    ["2", "b"],
  ];
  // the key itself changed in row 0: found by its old value
  const pending = { "1:1": null, "0:1": "A", "0:0": "10" };
  assert.deepEqual(buildEdits(["id", "name"], rows, ["id"], pending), [
    { key: [["id", "1"]], set: [["name", "A"], ["id", "10"]] },
    { key: [["id", "2"]], set: [["name", null]] },
  ]);
  assert.equal(changedRows(pending), 2);
  assert.deepEqual(withPending(rows, pending), [["10", "A"], ["2", null]]);
  assert.deepEqual(rows[0], ["1", "a"], "not changed in place");
});

test("queries whose rows are one table's rows", () => {
  assert.deepEqual(simpleSelect("select * from login_audit order by user_id desc limit 10;"), { schema: undefined, table: "login_audit", columns: null });
  assert.deepEqual(simpleSelect('SELECT id, l.name, "Weird" FROM sales.orders l WHERE x = \'join\''), {
    schema: "sales",
    table: "orders",
    columns: ["id", "name", "Weird"],
  });
  assert.deepEqual(simpleSelect("select o.* from orders o"), { schema: undefined, table: "orders", columns: null });
  for (const sql of [
    "select upper(name) as name from t",
    "select name n from t",
    "select a + 1 from t",
    "select * from a join b on true",
    "select * from a, b",
    "select status, count(*) from t group by status",
    "select distinct a from t",
    "select * from (select 1) s",
    "select * from t where id in (select id from u)",
    "update t set a = 1",
    "select 1",
  ]) {
    assert.equal(simpleSelect(sql), null, sql);
  }
});
